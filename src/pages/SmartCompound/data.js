export function getProposalData(services) {
  const subtotal = BASE_SUBTOTAL_EGP + (services ? SERVICES_ADDON_EGP : 0);
  const contingency = Math.round((subtotal * CONTINGENCY_PERCENT) / 100);
  const total = subtotal + contingency;

  const financialLines = services
    ? [...FINANCIAL_BASE, ...FINANCIAL_SERVICES]
    : [...FINANCIAL_BASE];

  const scope = services ? [...SCOPE_BASE, ...SCOPE_SERVICES] : [...SCOPE_BASE];

  const phases = services ? [...PHASES_BASE, PHASE_SERVICES] : [...PHASES_BASE];

  const milestones = services
    ? [
        ...MILESTONES_BASE.slice(0, 3),
        MILESTONE_SERVICES,
        { ...MILESTONES_BASE[3], weeksAr: "الأسابيع ~28–32" },
      ]
    : [...MILESTONES_BASE];

  const payment = PAYMENT_PERCENTS.map((m) => ({
    ...m,
    amount: Math.round((total * m.percent) / 100),
  }));

  const info = {
    ...PROJECT_BASE,
    subtotalEGP: subtotal,
    contingencyPercent: CONTINGENCY_PERCENT,
    contingencyEGP: contingency,
    totalEGP: total,
    durationWeeks: services ? "28–32" : "19–23",
    appsCount: 3,
    platformsAr: "iOS + Android + لوحة تحكم",
  };

  return { info, scope, milestones, phases, financialLines, payment, services };
}

